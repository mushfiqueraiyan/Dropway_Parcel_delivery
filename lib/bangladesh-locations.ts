const UPAZILAS_BY_DISTRICT: Record<string, string[]> = Object.fromEntries(
  DISTRICTS.map((district) => [district.name, district.upazilas]),
);

export const DISTRICT_NAMES: string[] = DISTRICTS.map(
  (district) => district.name,
).sort((a, b) => a.localeCompare(b));

export interface DivisionGroup {
  division: string;
  districts: string[];
}

export const DISTRICTS_BY_DIVISION: DivisionGroup[] = DISTRICTS.reduce(
  (groups, district) => {
    const group = groups.find((item) => item.division === district.division);

    if (group) {
      group.districts.push(district.name);
    } else {
      groups.push({ division: district.division, districts: [district.name] });
    }

    return groups;
  },
  [] as DivisionGroup[],
).map((group) => ({
  division: group.division,
  districts: [...group.districts].sort((a, b) => a.localeCompare(b)),
}));

export function getUpazilas(districtName: string): string[] {
  return UPAZILAS_BY_DISTRICT[districtName] ?? [];
}
